// Command gencrd writes the provider CRDs (stands in for controller-gen /
// upjet code generation so the generate-is-clean check has something real).
package main

import (
	"fmt"
	"os"
	"path/filepath"
)

type kind struct{ Kind, Plural, Group string }

var kinds = []kind{{Kind: "Widget", Plural: "widgets", Group: "selftest.ci.koorikla.dev"}}

const tmpl = `# Code generated by hack/gencrd. DO NOT EDIT.
apiVersion: apiextensions.k8s.io/v1
kind: CustomResourceDefinition
metadata:
  name: %[2]s.%[3]s
spec:
  group: %[3]s
  names:
    kind: %[1]s
    listKind: %[1]sList
    plural: %[2]s
    singular: %[4]s
    categories: [crossplane, managed]
  scope: Cluster
  versions:
    - name: v1alpha1
      served: true
      storage: true
      subresources:
        status: {}
      schema:
        openAPIV3Schema:
          type: object
          properties:
            spec:
              type: object
              properties:
                forProvider:
                  type: object
                  properties:
                    size:
                      type: integer
            status:
              type: object
              x-kubernetes-preserve-unknown-fields: true
`

func main() {
	out := "package/crds"
	if len(os.Args) > 1 {
		out = os.Args[1]
	}
	for _, k := range kinds {
		singular := k.Plural[:len(k.Plural)-1]
		body := fmt.Sprintf(tmpl, k.Kind, k.Plural, k.Group, singular)
		path := filepath.Join(out, fmt.Sprintf("%s_%s.yaml", k.Group, k.Plural))
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil { //nolint:gosec // CRDs are world-readable
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
}
