#!/usr/bin/env python3
"""Generate docs/reference/ from the platform's API sources (like helm-docs, but for XRDs and OpenChoreo types).

  gen-reference.py [--check] [ROOT]   (default ROOT: the repo root)

Sources, read with yq (+ helm for the chart, so templated ClusterWorkflows are included; stdlib Python otherwise):
  - packages/*/apis/*/definition.yaml           Crossplane XRDs                -> crossplane-apis.md
  - helm template addons/openchoreo-platform    ClusterComponentTypes, ClusterTraits, ClusterResourceTypes,
    + packages/*/openchoreo/*.yaml              ClusterWorkflows               -> openchoreo-<family>.md
Field tables come from each openAPIV3Schema: field (dotted path), type, required, default, description (+ limits).
--check writes nothing and exits 1 when docs/reference/ differs from what the sources generate (task lint, prek).
"""
import json
import os
import re
import subprocess
import sys

ARGS = [a for a in sys.argv[1:] if a != "--check"]
CHECK = "--check" in sys.argv[1:]
ROOT = os.path.abspath(ARGS[0] if ARGS else os.path.join(os.path.dirname(__file__), ".."))
OUT = os.path.join(ROOT, "docs", "reference")
CHART = "addons/openchoreo-platform"
HEADER = ("<!-- Generated by hack/gen-reference.py from {src}. Do not edit: change the source and run "
          "`task docs:reference`. -->\n")
FAMILIES = [  # (kind, page, title, intro)
    ("ClusterComponentType", "openchoreo-component-types.md", "OpenChoreo component types",
     "What a Component can be (`spec.componentType: deployment/<name>`); parameters are set on the Component, "
     "environment configs per environment on its ReleaseBinding."),
    ("ClusterTrait", "openchoreo-traits.md", "OpenChoreo traits",
     "Optional behaviour attached to a Component (`spec.traits[]`), within the component type's `allowedTraits`."),
    ("ClusterResourceType", "openchoreo-resource-types.md", "OpenChoreo resource types",
     "Managed dependencies a Workload binds (`dependencies.resources[]`); outputs reach the app as values or "
     "secretKeyRefs."),
    ("ClusterWorkflow", "openchoreo-workflows.md", "OpenChoreo workflows",
     "Build and gate workflows a Component runs (`spec.workflow`), within the component type's `allowedWorkflows`."),
]


def run(cmd, data=None):
    return subprocess.run(cmd, input=data, capture_output=True, text=True, check=True, cwd=ROOT).stdout


def yaml_docs(text):
    """Every YAML document in text as a JSON value (yq does the YAML parsing)."""
    s, dec, i, docs = run(["yq", "-o=json", "-I=0", "."], text), json.JSONDecoder(), 0, []
    while i < len(s):
        if s[i].isspace():
            i += 1
            continue
        doc, i = dec.raw_decode(s, i)
        if isinstance(doc, dict):
            docs.append(doc)
    return docs


def read(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
        return f.read()


def cell(v):
    return re.sub(r"\s+", " ", str(v)).strip().replace("|", "\\|")


def code(v):
    s = v if isinstance(v, str) else json.dumps(v, separators=(", ", ": "))
    return "`" + cell(s).replace("`", "'") + "`" if s != "" else '`""`'


def type_of(p):
    t = p.get("type", "")
    if t == "array":
        return type_of(p.get("items", {})) + "[]"
    if t == "object" and isinstance(p.get("additionalProperties"), dict):
        return "map[string]" + type_of(p["additionalProperties"])
    if p.get("x-kubernetes-preserve-unknown-fields") and not p.get("properties"):
        return "object (free-form)"
    return t or "any"


def limits(p):
    out = []
    if "enum" in p:
        out.append("One of " + ", ".join(code(e) for e in p["enum"]) + ".")
    lo, hi = p.get("minimum", p.get("minLength", p.get("minItems"))), p.get("maximum", p.get("maxLength", p.get("maxItems")))
    if lo is not None or hi is not None:
        unit = "" if "minimum" in p or "maximum" in p else (" items" if p.get("type") == "array" else " chars")
        out.append(f"Range {'' if lo is None else lo}..{'' if hi is None else hi}{unit}.")
    if "pattern" in p:
        out.append("Pattern " + code(p["pattern"]) + ".")
    if p.get("x-kubernetes-validations"):
        out.append("Rules: " + "; ".join(r.get("message", r.get("rule", "")) for r in p["x-kubernetes-validations"]) + ".")
    return " ".join(out)


def rows(schema, prefix=""):
    """Flatten an openAPIV3Schema object into (field, type, required, default, description) rows, source order."""
    if schema.get("type") == "array" and isinstance(schema.get("items"), dict):
        schema, prefix = schema["items"], prefix + "[]"
    req = set(schema.get("required", []))
    for name, p in (schema.get("properties") or {}).items():
        path = f"{prefix}.{name}" if prefix else name
        desc = " ".join(x for x in (cell(p.get("description", p.get("title", ""))), limits(p)) if x)
        yield (f"`{path}`", type_of(p), "yes" if name in req else "", code(p["default"]) if "default" in p else "", desc)
        yield from rows(p, path)


def table(schema, empty="No fields."):
    r = list(rows(schema or {}))
    if not r:
        return empty + "\n"
    lines = ["| Field | Type | Required | Default | Description |", "|---|---|---|---|---|"]
    return "\n".join(lines + ["| " + " | ".join(x) + " |" for x in r]) + "\n"


def page(title, src, intro, sections):
    toc = "\n".join(f"- [{name}](#{re.sub(r'[^a-z0-9 -]', '', name.lower()).replace(' ', '-')})" for name, _ in sections)
    body = "\n".join(f"## {name}\n\n{text}" for name, text in sections)
    return f"# {title}\n\n{HEADER.format(src=src)}\n{intro}\n\n{toc}\n\n{body}"


def crossplane_page():
    sections = []
    for pkg in sorted(os.listdir(os.path.join(ROOT, "packages"))):
        apis = os.path.join("packages", pkg, "apis")
        for api in sorted(os.listdir(os.path.join(ROOT, apis))) if os.path.isdir(os.path.join(ROOT, apis)) else []:
            rel = f"{apis}/{api}/definition.yaml"
            if not os.path.isfile(os.path.join(ROOT, rel)):
                continue
            for xrd in yaml_docs(read(rel)):
                spec, readme = xrd["spec"], f"packages/{pkg}/README.md"
                status = re.search(r"\*\*Status: ([^*]+)\*\*", read(readme)) if os.path.isfile(os.path.join(ROOT, readme)) else None
                for v in spec.get("versions", []):
                    schema = v.get("schema", {}).get("openAPIV3Schema", {}).get("properties", {})
                    text = (f"`apiVersion: {spec['group']}/{v['name']}`, `kind: {spec['names']['kind']}`, scope "
                            f"{spec.get('scope', 'Namespaced')}. Source: [{rel}](../../{rel}), package "
                            f"[README](../../{readme})" + (f" (status: {status.group(1).strip()})" if status else "") +
                            ".\n\n### spec\n\n" + table(schema.get("spec")) + "\n### status\n\n" + table(schema.get("status")))
                    sections.append((f"{spec['names']['kind']} {v['name']}", text))
    return page("Crossplane platform APIs", "packages/*/apis/*/definition.yaml",
                "Every platform API XRD (developer-facing contract: one namespaced XR, the cluster picks the backend). "
                "How they are built and installed: [crossplane.md](../crossplane.md); usage: "
                "[data-services.md](../data-services.md).", sections)


def openchoreo_objects():
    """(kind, name, source path, object) for the chart's rendered types and the packages' not-yet-deployed ones."""
    objs, rendered = [], run(["helm", "template", "openchoreo-platform", CHART])
    for chunk in re.split(r"(?m)^---\s*$", rendered):
        m = re.search(r"(?m)^kind: (Cluster(?:ComponentType|Trait|ResourceType|Workflow))\s*$", chunk)
        if m:
            # The last Source line names the file (templates that embed files/*.yaml add their own).
            src = re.findall(r"(?m)^# Source: openchoreo-platform/(\S+)", chunk)
            objs.append((f"{CHART}/{src[-1]}" if src else CHART, yaml_docs(chunk)[0], True))
    for pkg in sorted(os.listdir(os.path.join(ROOT, "packages"))):
        d = f"packages/{pkg}/openchoreo"
        for f in sorted(os.listdir(os.path.join(ROOT, d))) if os.path.isdir(os.path.join(ROOT, d)) else []:
            objs += [(f"{d}/{f}", o, False) for o in yaml_docs(read(f"{d}/{f}"))]
    return objs


def openchoreo_section(src, o, deployed):
    spec, ann = o.get("spec", {}), o["metadata"].get("annotations") or {}
    desc = cell(ann.get("openchoreo.dev/description", ""))
    facts = [desc + ("" if not desc or desc[-1] in ".!?" else "."), f"Source: [{src}](../../{src})."]
    if not deployed:
        facts.append("**Not deployed yet**: the API package is still a layout; the file moves into the chart when enabled.")
    for key, label in (("workloadType", "Workload type"), ("allowedTraits", "Allowed traits"),
                       ("allowedWorkflows", "Allowed workflows")):
        if key in spec:
            v = spec[key]
            v = ", ".join(sorted(x.get("name", "") if isinstance(x, dict) else str(x) for x in v)) if isinstance(v, list) else v
            facts.append(f"{label}: {v or 'none'}.")
    if ann.get("platform.koorikla.io/requires-addons"):
        facts.append(f"Needs data-plane addons: {ann['platform.koorikla.io/requires-addons']}.")
    text = " ".join(x for x in facts if x) + "\n"
    for key in ("parameters", "environmentConfigs"):
        if key in spec:
            text += f"\n### {key}\n\n" + table(spec[key].get("openAPIV3Schema"))
    if spec.get("outputs"):
        text += "\n### outputs\n\n| Output | Delivered as |\n|---|---|\n" + "".join(
            f"| `{x['name']}` | {'secretKeyRef ' + code(x['secretKeyRef'].get('key', '')) if 'secretKeyRef' in x else 'value'} |\n"
            for x in spec["outputs"])
    return text


def generate():
    pages = {"crossplane-apis.md": crossplane_page()}
    objs = openchoreo_objects()
    for kind, name, title, intro in FAMILIES:
        found = sorted((o for o in objs if o[1].get("kind") == kind), key=lambda o: (not o[2], o[1]["metadata"]["name"]))
        pages[name] = page(title, f"helm template {CHART} + packages/*/openchoreo/", intro,
                           [(o[1]["metadata"]["name"], openchoreo_section(*o)) for o in found])
    index = [f"- [{t}]({p})" for p, t in [("crossplane-apis.md", "Crossplane platform APIs")] + [(f[1], f[2]) for f in FAMILIES]]
    pages["README.md"] = (f"# Reference\n\n{HEADER.format(src='the sources listed on each page')}\nGenerated from the "
                          "platform's API sources, so they never drift from the code (CI fails when stale).\n\n" +
                          "\n".join(index) + "\n")
    return pages


def main():
    pages, problems = generate(), []
    existing = set(os.listdir(OUT)) if os.path.isdir(OUT) else set()
    for name, text in sorted(pages.items()):
        path = os.path.join(OUT, name)
        old = read(os.path.relpath(path, ROOT)) if name in existing else None
        if old != text:
            problems.append(name)
            if not CHECK:
                os.makedirs(OUT, exist_ok=True)
                with open(path, "w", encoding="utf-8", newline="\n") as f:
                    f.write(text)
    for name in sorted(existing - set(pages)):
        problems.append(name + " (no source)")
        if not CHECK:
            os.remove(os.path.join(OUT, name))
    if CHECK and problems:
        print("docs/reference/ is stale: " + ", ".join(problems) + ". Run `task docs:reference`.", file=sys.stderr)
        sys.exit(1)
    print(("reference docs OK" if CHECK else f"reference docs: {len(problems)} page(s) updated") + f" ({len(pages)} pages)")


if __name__ == "__main__":
    main()
